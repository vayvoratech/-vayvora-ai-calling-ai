from typing import Any, TypedDict


class AgentState(TypedDict, total=False):
    # ─────────────────────────────────────────────
    # CALL / SESSION
    # ─────────────────────────────────────────────
    call_id: str
    session_id: str

    # ─────────────────────────────────────────────
    # USER INPUT
    # ─────────────────────────────────────────────
    user_input: str

    # ─────────────────────────────────────────────
    # CONVERSATION
    # ─────────────────────────────────────────────
    messages: list[dict[str, Any]]

    # ─────────────────────────────────────────────
    # FAST LOCAL ROUTER
    # ─────────────────────────────────────────────
    route: str
    route_confidence: float

    # Possible routes:
    # direct
    # llm
    # rag
    # mcp

    # ─────────────────────────────────────────────
    # REDIS MEMORY / CACHE
    # ─────────────────────────────────────────────
    memory_context: list[str]
    memory_hit: bool

    # ─────────────────────────────────────────────
    # RAG
    # ─────────────────────────────────────────────
    rag_required: bool
    rag_context: list[str]

    # ─────────────────────────────────────────────
    # MCP / TOOLS
    # ─────────────────────────────────────────────
    tool_required: bool
    tool_name: str
    tool_input: dict[str, Any]
    tool_result: Any

    # ─────────────────────────────────────────────
    # LLM
    # ─────────────────────────────────────────────
    llm_required: bool

    # ─────────────────────────────────────────────
    # FINAL RESPONSE
    # ─────────────────────────────────────────────
    response: str

    # ─────────────────────────────────────────────
    # CONTROL
    # ─────────────────────────────────────────────
    is_complete: bool

    # ─────────────────────────────────────────────
    # ERROR HANDLING
    # ─────────────────────────────────────────────
    error: str | None