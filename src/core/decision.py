"""Structured conversational decision schema and validation logic.

Defines the structured output contract expected from Gemini 3.5 Flash,
distinguishing proposed actions, grounding queries, and stage advancements.
"""

import re
from typing import TYPE_CHECKING, Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, computed_field, field_validator, model_validator

from src.core.errors import DecisionValidationError
from src.core.types import ConversationStage, DomainType

if TYPE_CHECKING:
    from src.domains.registry import DomainRegistry


class ProposedAction(BaseModel):
    """Specification of an external tool action proposed by the LLM."""

    model_config = ConfigDict(extra="ignore")

    tool_name: str = Field(..., min_length=1, description="Registered identifier of the MCP tool")
    arguments: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured arguments prepared for the proposed tool invocation",
    )
    rationale: Optional[str] = Field(
        default=None,
        description="Reasoning why this action is being proposed at this conversational turn",
    )

    @field_validator("tool_name")
    @classmethod
    def normalize_tool_name(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("tool_name must not be blank")
        return cleaned


class ConversationalDecision(BaseModel):
    """Structured turn decision generated by the LLM."""

    model_config = ConfigDict(extra="ignore")

    detected_domain: DomainType = Field(
        default=DomainType.INFRA_BUILDER,
        description="Business domain identified from caller's latest utterance or trusted state",
    )
    detected_intent: Optional[str] = Field(
        default=None,
        description="Specific intent classified for this turn",
    )
    detected_sub_intent: Optional[str] = Field(
        default=None,
        description="Sub-intent or specialization if applicable",
    )
    extracted_slots: Dict[str, Any] = Field(
        default_factory=dict,
        description="Entity values extracted from current utterance or dialogue",
    )
    proposed_stage: ConversationStage = Field(
        default=ConversationStage.INFORMATION,
        description="Recommended conversation stage progression",
    )
    user_facing_response: str = Field(
        default="",
        description="Natural conversational utterance to be voiced to the caller (empty when knowledge_required is True)",
    )
    knowledge_required: bool = Field(
        default=False,
        description="True if factual grounding is needed from the domain knowledge base (RAG)",
    )
    knowledge_query: Optional[str] = Field(
        default=None,
        description="Semantic search query text for RAG retrieval if knowledge is required",
    )
    proposed_action: Optional[ProposedAction] = Field(
        default=None,
        description="Details of proposed action; MUST NOT be treated as already executed",
    )

    @computed_field
    @property
    def action_proposed(self) -> bool:
        """Authoritatively derived from proposed_action presence."""
        return self.proposed_action is not None

    @action_proposed.setter
    def action_proposed(self, value: bool) -> None:
        """Compatibility setter ensuring action_proposed never diverges from proposed_action.

        Setting action_proposed=False clears proposed_action.
        Setting action_proposed=True is a no-op if proposed_action is already set,
        and never fabricates an action if proposed_action is None.
        """
        if not value:
            self.proposed_action = None

    needs_clarification: bool = Field(
        default=False,
        description="True if caller's intent was ambiguous or underspecified",
    )
    clarification_question: Optional[str] = Field(
        default=None,
        description="Clarification question to ask caller if needs_clarification is True",
    )
    suggested_termination: bool = Field(
        default=False,
        description="Advisory signal from LLM; must still pass explicit termination validation",
    )

    @field_validator("user_facing_response", mode="before")
    @classmethod
    def normalize_user_facing_response(cls, value: Any) -> str:
        if value is None:
            return ""
        return str(value)

    @model_validator(mode="after")
    def validate_user_facing_response_presence(self) -> "ConversationalDecision":
        """Ensure non-RAG turns provide a spoken response unless terminating."""
        if not self.knowledge_required and not self.suggested_termination:
            if not self.user_facing_response or not self.user_facing_response.strip():
                raise ValueError("user_facing_response must not be blank when knowledge_required is false")
        return self


    @field_validator("detected_domain", mode="before")
    @classmethod
    def normalize_domain(cls, value: Any) -> Any:
        """Accept only the active business and shared routing states."""
        if value is None:
            return DomainType.INFRA_BUILDER

        if isinstance(value, DomainType):
            if value in (DomainType.INFRA_BUILDER, DomainType.GENERAL, DomainType.UNKNOWN):
                return value
            return DomainType.UNKNOWN

        if isinstance(value, str):
            cleaned = value.strip().lower().replace("-", "_").replace(" ", "_")
            if cleaned in {"infra_builder", "infrabuilder", "infra_builder_real_estate"}:
                return DomainType.INFRA_BUILDER
            if cleaned == "general":
                return DomainType.GENERAL
            if cleaned == "unknown":
                return DomainType.UNKNOWN
            return DomainType.UNKNOWN

        return DomainType.UNKNOWN

    @field_validator("detected_intent", "detected_sub_intent", mode="before")
    @classmethod
    def normalize_intent_labels(cls, value: Any) -> Optional[str]:
        if value is None or not isinstance(value, str):
            return None
        cleaned = value.strip().lower().replace("-", "_").replace(" ", "_")
        return cleaned or None

    @field_validator("proposed_stage", mode="before")
    @classmethod
    def normalize_stage(cls, v: Any) -> Any:
        if isinstance(v, str):
            clean = v.strip().lower()
            try:
                return ConversationStage(clean)
            except ValueError:
                return ConversationStage.INFORMATION
        return v

    @field_validator("proposed_action", mode="before")
    @classmethod
    def normalize_proposed_action(cls, value: Any) -> Any:
        """Normalize common LLM action aliases before ProposedAction validation.

        The canonical internal field is ``tool_name``. Some model responses use
        ``tool`` instead; accept that alias without changing downstream code.
        If both are present, an explicit ``tool_name`` takes precedence.
        """
        if value is None:
            return None
        if isinstance(value, str) and value.strip().lower() in {"", "null", "none"}:
            return None
        if isinstance(value, dict):
            normalized = dict(value)
            if not normalized.get("tool_name") and normalized.get("tool"):
                normalized["tool_name"] = normalized["tool"]
            normalized.pop("tool", None)
            return normalized
        return value


# Compile extraction patterns once at import time. This avoids recompiling the same
# expressions on every caller turn, which is important in a latency-sensitive loop.
_TIME_PART = r'(?:\d{1,2}(?::[0-5]\d)?\s*(?:am|pm|a\.m\.|p\.m\.)|\b(?:morning|afternoon|evening|night|noon|midnight)\b)'
_TZ_PART = r'(?:\s+(?:ist|est|pst|cst|utc|gmt|edt|pdt))?'
_DATE_PART = (
    r'(?:today|tomorrow|yesterday|'
    r'(?:this\s+|next\s+)?(?:monday|tuesday|wednesday|thursday|friday|saturday|sunday)|'
    r'(?:jan(?:uary)?|feb(?:ruary)?|mar(?:ch)?|apr(?:il)?|may|jun(?:e)?|jul(?:y)?|aug(?:ust)?|sep(?:tember)?|oct(?:ober)?|nov(?:ember)?|dec(?:ember)?)\s+\d{1,2}(?:st|nd|rd|th)?'
    r')'
)
_DATETIME_PATTERNS = (
    re.compile(rf'\b({_DATE_PART}(?:\s+(?:by|at|around|on|for))?\s+{_TIME_PART}{_TZ_PART})\b', re.IGNORECASE),
    re.compile(rf'\b({_TIME_PART}{_TZ_PART}(?:\s+(?:on|for|by|at))?\s+{_DATE_PART})\b', re.IGNORECASE),
    re.compile(rf'\b({_DATE_PART}\s+(?:morning|afternoon|evening|noon|night))\b', re.IGNORECASE),
    re.compile(rf'(?:make\s+it\s+|at\s+|by\s+|for\s+)?\b({_TIME_PART}{_TZ_PART})\b(?:\s+instead)?', re.IGNORECASE),
)
_SCHEDULING_RE = re.compile(r'\b(schedule|meeting|consultation|demo|book|call|appointment|slot|site\s+visit)\b', re.IGNORECASE)
_STANDALONE_DATE_RE = re.compile(rf'^(?:yes,?\s*|sure,?\s*|for\s+|on\s+)?{_DATE_PART}[.!?]?$', re.IGNORECASE)
_BARE_DATE_RE = re.compile(rf'\b({_DATE_PART})\b', re.IGNORECASE)


def extract_datetime_preference(text: str) -> Optional[str]:
    """Extract a caller's stated date/time preference without resolving it.

    This is lexical extraction only. The booking layer must resolve relative dates,
    timezone, past dates, and actual calendar availability before scheduling.
    """
    if not isinstance(text, str) or not text.strip():
        return None

    cleaned = text.strip()
    for index, pattern in enumerate(_DATETIME_PATTERNS):
        match = pattern.search(cleaned)
        if not match:
            continue
        candidate = match.group(1).strip()
        # A bare time-of-day phrase is too vague to be a complete appointment time.
        if index == 3 and not re.search(r'\d|\b(?:noon|midnight)\b', candidate, re.IGNORECASE):
            continue
        return candidate

    if _SCHEDULING_RE.search(cleaned) or _STANDALONE_DATE_RE.fullmatch(cleaned):
        match = _BARE_DATE_RE.search(cleaned)
        if match:
            return match.group(1).strip()
    return None


class DecisionValidator:
    """Validates ConversationalDecision instances against domain rules and registries."""

    def __init__(self, registry: Optional["DomainRegistry"] = None) -> None:
        if registry is None:
            from src.domains.registry import get_domain_registry
            registry = get_domain_registry()
        self.registry = registry

    def validate_and_filter(
        self, decision: ConversationalDecision
    ) -> ConversationalDecision:
        """Validate decision fields, sanitize slots, and return verified decision."""
        # 1. Validate Domain
        domain_config = self.registry.get(decision.detected_domain)
        if not domain_config:
            raise DecisionValidationError(
                f"Unknown domain detected: '{decision.detected_domain}'"
            )

        # 2. Validate intent before accepting any proposed external mutation.
        # Unknown labels are recovered safely rather than crashing the call. An
        # unsupported intent must never authorize a tool action by itself.
        unsupported_intent = False
        if decision.detected_intent:
            intent_clean = decision.detected_intent.strip().lower()
            if not domain_config.is_intent_supported(intent_clean):
                unsupported_intent = True
                decision.detected_intent = "fallback" if domain_config.is_intent_supported("fallback") else None
                decision.detected_sub_intent = None
                decision.proposed_action = None
                decision.action_proposed = False

        # 3. Canonicalize date/time aliases deterministically.
        # An explicit canonical value wins; otherwise use a stable alias order.
        raw_slots = decision.extracted_slots if isinstance(decision.extracted_slots, dict) else {}
        cleaned_slots: Dict[str, Any] = {}
        for key, value in raw_slots.items():
            if not isinstance(key, str):
                continue
            key_clean = key.strip().lower()
            if key_clean and value is not None and str(value).strip():
                cleaned_slots[key_clean] = value

        if not cleaned_slots.get("meeting_preference"):
            date_value = cleaned_slots.get("preferred_date") or cleaned_slots.get("date")
            time_value = cleaned_slots.get("preferred_time")
            if date_value and time_value:
                cleaned_slots["meeting_preference"] = f"{str(date_value).strip()} {str(time_value).strip()}"
            else:
                for alias in ("meeting_time", "appointment_time", "calendar_slot", "slot", "time", "preferred_date", "date", "preferred_time"):
                    value = cleaned_slots.get(alias)
                    if value is not None and str(value).strip():
                        cleaned_slots["meeting_preference"] = str(value).strip()
                        break

        # Preserve a slot proposed by the model only when the caller/state slots
        # did not already supply a preference. Execution still validates it later.
        if decision.proposed_action and decision.proposed_action.tool_name == "create_calendar_event":
            args = decision.proposed_action.arguments
            action_slot = args.get("slot") or args.get("start_time") or args.get("time")
            if action_slot and str(action_slot).strip() and not cleaned_slots.get("meeting_preference"):
                cleaned_slots["meeting_preference"] = str(action_slot).strip()

        # 4. Validate & Filter Slots
        sanitized_slots: Dict[str, Any] = {}
        allowed_slot_names = set(domain_config.get_slot_names())
        # Universal caller slots are always allowed across ALL domains
        universal_slots = {
            "name",
            "contact_name",
            "phone",
            "email",
            "meeting_preference",
            "preferred_project",
            "property_type",
            "configuration",
            "budget",
            "whatsapp_consent",
        }

        for k_clean, val in cleaned_slots.items():
            if k_clean in allowed_slot_names or k_clean in universal_slots:
                if val is None or not str(val).strip():
                    continue
                if k_clean == "whatsapp_consent":
                    if isinstance(val, bool):
                        sanitized_slots[k_clean] = val
                    elif isinstance(val, str):
                        consent_value = val.strip().lower()
                        if consent_value in {"yes", "true", "consented", "approved", "authorized"}:
                            sanitized_slots[k_clean] = True
                        elif consent_value in {"no", "false", "refused", "denied", "declined"}:
                            sanitized_slots[k_clean] = False
                    continue
                sanitized_slots[k_clean] = val

        # 5. Action Validation & Normalization.
        # Only actions implemented by the tool layer may leave this validator.
        # Never translate a real-estate advisor callback into an HR follow-up:
        # that would invoke a semantically unrelated tool.
        supported_actions = {
            "send_email",
            "find_available_slots",
            "create_calendar_event",
            "cancel_calendar_event",
            "calendar_cancel_event",
            "update_lead",
            "create_hr_followup",
            "send_message",
            "update_business_status",
            "mail_read_recent",
        }
        infra_builder_blocked_actions = {"send_email", "mail_read_recent", "create_hr_followup"}

        if decision.proposed_action:
            tool_name = decision.proposed_action.tool_name.strip()
            decision.proposed_action.tool_name = tool_name
            blocked_for_domain = (
                decision.detected_domain == DomainType.INFRA_BUILDER
                and tool_name in infra_builder_blocked_actions
            )
            unconfirmed_cancellation = (
                tool_name in ("cancel_calendar_event", "calendar_cancel_event")
                and decision.proposed_action.arguments.get("confirmed") is not True
            )

            # A current-turn refusal overrides a proposed message. The trusted
            # tool/engine layer must independently enforce affirmative consent.
            if (
                tool_name not in supported_actions
                or blocked_for_domain
                or unconfirmed_cancellation
                or (tool_name == "send_message" and sanitized_slots.get("whatsapp_consent") is False)
                or unsupported_intent
            ):
                # Keep the conversational response; suppress only the unsafe action.
                decision.proposed_action = None
                decision.action_proposed = False
            else:
                decision.action_proposed = True
        elif decision.action_proposed:
            decision.action_proposed = False

        # 6. Knowledge query consistency. Avoid unnecessary retrieval queries.
        if decision.knowledge_required:
            query = decision.knowledge_query.strip() if isinstance(decision.knowledge_query, str) else ""
            decision.knowledge_query = query or decision.detected_intent or "general inquiry"
        else:
            decision.knowledge_query = None

        # 7. Keep the action flag consistent with the validated payload.
        if decision.proposed_action is None:
            decision.action_proposed = False
        elif not unsupported_intent:
            decision.action_proposed = True

        decision.extracted_slots = sanitized_slots
        return decision


